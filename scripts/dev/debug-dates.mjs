import { chromium } from '@playwright/test'
const url = process.argv[2] || 'http://127.0.0.1:5174/'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
const errors = []
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message))
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()) })
await page.goto(url)
await page.waitForTimeout(1500)
console.log('cards', await page.getByTestId('date-card').count(), 'focused', await page.evaluate(() => document.activeElement?.getAttribute('data-iso')))
await page.screenshot({ path: 'scripts/dev/out-landing.png' })
await page.keyboard.press('Enter')
await page.waitForTimeout(1500)
console.log('act1', await page.getByTestId('journey-act1').isVisible(), await page.getByTestId('days-counter').innerText())
await page.screenshot({ path: 'scripts/dev/out-act1a.png' })
await page.waitForTimeout(3200)
console.log('t4.7', (await page.getByTestId('days-counter').innerText()).replace(/\n/g,' | '))
await page.screenshot({ path: 'scripts/dev/out-act1b.png' })
await page.waitForTimeout(3500)
console.log('t8.2', (await page.getByTestId('days-counter').innerText()).replace(/\n/g,' | '))
await page.screenshot({ path: 'scripts/dev/out-act1c.png' })
await page.waitForTimeout(5000)
console.log('t13', 'slot visible', await page.getByTestId('slot').isVisible())
await page.screenshot({ path: 'scripts/dev/out-after.png' })
console.log('errors', errors)
await browser.close()
